"""
Master Bell States Simulator (NumPy + Tkinter + Matplotlib)
-----------------------------------------------------------
Combines explicit linear algebra (tensor products, matrix gates) 
with a sleek graphical desktop interface and live measurement histograms.

Install requirements:
    python -m pip install numpy matplotlib

Run:
    python bell_simulator_master.py
"""

import tkinter as tk
from tkinter import ttk, messagebox
import numpy as np

import matplotlib
matplotlib.use("TkAgg")
from matplotlib.backends.backend_tkagg import FigureCanvasTkAgg
from matplotlib.figure import Figure
import bell_states_simulatoree as engine



# ==========================================
# QUANTUM ENGINE — OUR UPDATED IMPLEMENTATION
# ==========================================

H = engine.H
I = engine.I
X = engine.X
Z = engine.Z
CNOT = engine.CNOT

INITIAL_STATE = engine.initial_state
OUTCOMES = engine.OUTCOMES

# Use the Bell states generated by our updated engine
ENGINE_BELL_STATES = engine.create_bell_states()

BELL_STATES_DICT = {
    "Φ⁺ (|00⟩ + |11⟩) / √2": ENGINE_BELL_STATES["1"][1],
    "Φ⁻ (|00⟩ - |11⟩) / √2": ENGINE_BELL_STATES["2"][1],
    "Ψ⁺ (|01⟩ + |10⟩) / √2": ENGINE_BELL_STATES["3"][1],
    "Ψ⁻ (|01⟩ - |10⟩) / √2": ENGINE_BELL_STATES["4"][1],
}


def recognize_bell_state(state):
    return engine.recognize_bell_state(
        state, ENGINE_BELL_STATES
    )



# ==========================================
# GUI APPLICATION CLASS
# ==========================================

class MasterBellSimulatorApp:
    def __init__(self, root):
        self.root = root
        self.root.title("Master Bell States Simulator — Linear Algebra & Visualization")
        self.root.geometry("1200x800")
        self.root.minsize(950, 700)

        # Active working state vector for the builder tab
        self.current_builder_state = INITIAL_STATE.copy()

        self._build_ui()
        self.run_preset_simulation()

    def _build_ui(self):
        # Header
        header = ttk.Frame(self.root, padding=(16, 12))
        header.pack(fill="x")
        ttk.Label(
            header, text="QUANTUM ENTANGLEMENT & BELL STATES",
            font=("Arial", 18, "bold")
        ).pack(anchor="w")
        ttk.Label(
            header,
            text="Powered by NumPy matrix algebra, interactive state tracking, and live sampling.",
            font=("Arial", 10)
        ).pack(anchor="w", pady=(2, 4))

        # Main Layout using Notebook (Tabs) for Modes
        self.notebook = ttk.Notebook(self.root)
        self.notebook.pack(fill="both", expand=True, padx=16, pady=(0, 8))

        # TAB 1: Preset Bell States & Sampling
        self.tab_presets = ttk.Frame(self.notebook, padding=10)
        self.notebook.add(self.tab_presets, text="  1. Preset Bell States  ")

        # TAB 2: Step-by-Step Circuit Builder
        self.tab_builder = ttk.Frame(self.notebook, padding=10)
        self.notebook.add(self.tab_builder, text="  2. Step-by-Step Circuit Builder  ")

        self.notebook.bind("<<NotebookTabChanged>>", self._on_tab_change)

        self._build_preset_tab()
        self._build_builder_tab()

    def _build_preset_tab(self):
        frame = self.tab_presets
        
        controls = ttk.Frame(frame, padding=(0, 5, 0, 10))
        controls.pack(fill="x")

        ttk.Label(controls, text="Select Bell State:").pack(side="left", padx=(0, 8))
        self.preset_var = tk.StringVar(value=list(BELL_STATES_DICT.keys())[0])
        selector = ttk.Combobox(
            controls, textvariable=self.preset_var,
            values=list(BELL_STATES_DICT.keys()), state="readonly", width=30
        )
        selector.pack(side="left", padx=(0, 15))
        selector.bind("<<ComboboxSelected>>", lambda _: self.run_preset_simulation())

        ttk.Label(controls, text="Shots:").pack(side="left", padx=(0, 5))
        self.shots_var = tk.StringVar(value="1000")
        shots_entry = ttk.Entry(controls, textvariable=self.shots_var, width=8)
        shots_entry.pack(side="left", padx=(0, 12))

        ttk.Button(controls, text="Run Simulation", command=self.run_preset_simulation).pack(side="left")

        # Split pane for Info (left) and Chart (right)
        paned = ttk.Panedwindow(frame, orient="horizontal")
        paned.pack(fill="both", expand=True, pady=5)

        left_pane = ttk.Frame(paned, padding=5)
        right_pane = ttk.Frame(paned, padding=5)
        paned.add(left_pane, weight=1)
        paned.add(right_pane, weight=2)

        ttk.Label(left_pane, text="MATHEMATICAL STATE VECTOR", font=("Arial", 11, "bold")).pack(anchor="w")
        self.preset_state_text = tk.Text(left_pane, height=10, width=38, font=("Courier New", 10), state="disabled")
        self.preset_state_text.pack(fill="x", pady=(5, 10))

        ttk.Label(left_pane, text="PHYSICAL INTERPRETATION", font=("Arial", 11, "bold")).pack(anchor="w")
        self.preset_info_label = ttk.Label(left_pane, text="", wraplength=350, justify="left")
        self.preset_info_label.pack(anchor="w", pady=(5, 0))

        # Matplotlib Chart Setup
        ttk.Label(right_pane, text="MEASUREMENT PROBABILITIES (THEORY vs SAMPLED)", font=("Arial", 11, "bold")).pack(anchor="w")
        self.fig1 = Figure(figsize=(6, 4.5), dpi=100, tight_layout=True)
        self.ax1 = self.fig1.add_subplot(111)
        self.canvas1 = FigureCanvasTkAgg(self.fig1, master=right_pane)
        self.canvas1.get_tk_widget().pack(fill="both", expand=True, pady=(5, 0))

    def _build_builder_tab(self):
        frame = self.tab_builder

        paned = ttk.Panedwindow(frame, orient="horizontal")
        paned.pack(fill="both", expand=True, pady=5)

        left_pane = ttk.Frame(paned, padding=5)
        right_pane = ttk.Frame(paned, padding=5)
        paned.add(left_pane, weight=1)
        paned.add(right_pane, weight=2)

        ttk.Label(left_pane, text="APPLY QUANTUM GATES", font=("Arial", 11, "bold")).pack(anchor="w", pady=(0, 5))
        
        buttons_frame = ttk.Frame(left_pane)
        buttons_frame.pack(fill="x", pady=5)

        ttk.Button(buttons_frame, text="Apply H to Qubit 0", command=lambda: self.apply_gate("H0")).pack(fill="x", pady=2)
        ttk.Button(buttons_frame, text="Apply X to Qubit 0", command=lambda: self.apply_gate("X0")).pack(fill="x", pady=2)
        ttk.Button(buttons_frame, text="Apply Z to Qubit 0", command=lambda: self.apply_gate("Z0")).pack(fill="x", pady=2)
        ttk.Button(buttons_frame, text="Apply H to Qubit 1", command=lambda: self.apply_gate("H1")).pack(fill="x", pady=2)
        ttk.Button(buttons_frame, text="Apply X to Qubit 1", command=lambda: self.apply_gate("X1")).pack(fill="x", pady=2)
        ttk.Button(buttons_frame, text="Apply Z to Qubit 1", command=lambda: self.apply_gate("Z1")).pack(fill="x", pady=2)
        ttk.Button(buttons_frame, text="Apply CNOT (Q0 ➔ Q1)", command=lambda: self.apply_gate("CNOT")).pack(fill="x", pady=2)
        ttk.Button(buttons_frame, text="Reset State to |00⟩", command=self.reset_builder).pack(fill="x", pady=(15, 2))

        ttk.Label(left_pane, text="STATE VECTOR & RECOGNITION", font=("Arial", 11, "bold")).pack(anchor="w", pady=(10, 5))
        self.builder_state_text = tk.Text(left_pane, height=9, width=38, font=("Courier New", 10), state="disabled")
        self.builder_state_text.pack(fill="x", pady=(5, 0))

        # Right pane for Builder chart/status
        ttk.Label(right_pane, text="LIVE CIRCUIT PROBABILITIES", font=("Arial", 11, "bold")).pack(anchor="w")
        self.fig2 = Figure(figsize=(6, 4.5), dpi=100, tight_layout=True)
        self.ax2 = self.fig2.add_subplot(111)
        self.canvas2 = FigureCanvasTkAgg(self.fig2, master=right_pane)
        self.canvas2.get_tk_widget().pack(fill="both", expand=True, pady=(5, 0))

    def _set_text(self, widget, text):
        widget.configure(state="normal")
        widget.delete("1.0", "end")
        widget.insert("1.0", text)
        widget.configure(state="disabled")

    def run_preset_simulation(self):
        label = self.preset_var.get()
        state = BELL_STATES_DICT[label]

        try:
            shots = int(self.shots_var.get())
            if shots <= 0:
                shots = 1000
        except ValueError:
            shots = 1000

        # Format state vector amplitudes
        amp_lines = []
        for i, outcome in enumerate(OUTCOMES):
            amp = state[i]
            amp_lines.append(f"{outcome} : {amp.real:+.3f}{amp.imag:+.3f}i")
        
        norm = np.linalg.norm(state)
        state_summary = "\n".join(amp_lines) + f"\n\nNorm: {norm:.4f} (Valid)"
        self._set_text(self.preset_state_text, state_summary)

        # Explanations
        info_dict = {
            "Φ⁺ (|00⟩ + |11⟩) / √2": "Maximally entangled state. Measuring either qubit yields 0 or 1 with 50% probability. If Q0 is measured as 0, Q1 is guaranteed to be 0.",
            "Φ⁻ (|00⟩ - |11⟩) / √2": "Entangled state with a negative relative phase (-1). Produces identical measurement correlations to Φ⁺, but exhibits distinct interference behavior.",
            "Ψ⁺ (|01⟩ + |10⟩) / √2": "Maximally entangled state where the two qubits always yield opposite measurement results (one is 0, the other is 1).",
            "Ψ⁻ (|01⟩ - |10⟩) / √2": "Entangled singlet state with a relative minus phase. Rotational invariant, widely used in quantum cryptography and teleportation protocols."
        }
        self.preset_info_label.configure(text=info_dict[label])

        # Probabilities & Sampling
        probabilities = np.abs(state) ** 2
        sampled_results = np.random.choice(OUTCOMES, size=shots, p=probabilities)
        counts = [np.count_nonzero(sampled_results == out) for out in OUTCOMES]
        measured_probs = np.array(counts) / shots * 100
        theo_probs = probabilities * 100

        # Plotting
        self.ax1.clear()
        x = np.arange(len(OUTCOMES))
        width = 0.35
        self.ax1.bar(x - width/2, theo_probs, width, label="Theoretical (%)")
        self.ax1.bar(x + width/2, measured_probs, width, label=f"Measured ({shots} shots)")
        self.ax1.set_xticks(x)
        self.ax1.set_xticklabels(OUTCOMES)
        self.ax1.set_ylabel("Percentage (%)")
        self.ax1.set_ylim(0, 105)
        self.ax1.set_title(f"State: {label.split()[0]}")
        self.ax1.legend(loc="upper right")
        self.ax1.grid(axis="y", linestyle="--", alpha=0.4)
        self.canvas1.draw()

    def update_builder_display(self):
        state = self.current_builder_state
        amp_lines = []
        for i, outcome in enumerate(OUTCOMES):
            amp = state[i]
            amp_lines.append(f"{outcome} : {amp.real:+.3f}{amp.imag:+.3f}i")

        bell_name = recognize_bell_state(state)
        status_str = f"\nRecognized Bell State: {bell_name}" if bell_name else "\nState: Superposition / Product state"
        
        summary = "\n".join(amp_lines) + status_str
        self._set_text(self.builder_state_text, summary)

        # Plot live probabilities
        probabilities = np.abs(state) ** 2
        self.ax2.clear()
        self.ax2.bar(OUTCOMES, probabilities * 100, color="teal")
        self.ax2.set_ylabel("Probability (%)")
        self.ax2.set_ylim(0, 105)
        title = f"Current State Probabilities" + (f" [{bell_name}]" if bell_name else "")
        self.ax2.set_title(title)
        self.ax2.grid(axis="y", linestyle="--", alpha=0.4)
        self.canvas2.draw()

    def apply_gate(self, gate_type):
        if gate_type == "H0":
            op = np.kron(H, I)
        elif gate_type == "X0":
            op = np.kron(X, I)
        elif gate_type == "Z0":
            op = np.kron(Z, I)
        elif gate_type == "H1":
            op = np.kron(I, H)
        elif gate_type == "X1":
            op = np.kron(I, X)
        elif gate_type == "Z1":
            op = np.kron(I, Z)
        elif gate_type == "CNOT":
            op = CNOT
        else:
            return

        self.current_builder_state = op @ self.current_builder_state
        self.update_builder_display()

    def reset_builder(self):
        self.current_builder_state = INITIAL_STATE.copy()
        self.update_builder_display()

    def _on_tab_change(self, event):
        selected_tab = self.notebook.index(self.notebook.select())
        if selected_tab == 1:
            self.update_builder_display()


def main():
    root = tk.Tk()
    try:
        style = ttk.Style()
        if "clam" in style.theme_names():
            style.theme_use("clam")
    except tk.TclError:
        pass
    MasterBellSimulatorApp(root)
    root.mainloop()


if __name__ == "__main__":
    main()